_SUFFIXES = ["", "。", "〜", "…", " 😌", " ☕", " 🌙"]
_PREFIXES = ["", "ふと、", "なんか、", "正直、"]


def pick_casual_text(*, rng: random.Random | None = None) -> str:
    """テンプレを1件選び、軽い言い換えで重複感を減らす。"""
    r = rng or random
    base = r.choice(CASUAL_TEMPLATES)
    prefix = r.choice(_PREFIXES)
    suffix = r.choice(_SUFFIXES)
    # 接頭辞は低確率
    if r.random() > 0.35:
        prefix = ""
    text = f"{prefix}{base}{suffix}".strip()
    return text
